package com.fxrates.di

import com.arkivanov.decompose.ComponentContext
import com.arkivanov.mvikotlin.core.store.StoreFactory
import com.arkivanov.mvikotlin.main.store.DefaultStoreFactory
import com.fxrates.data.remote.createHttpClient
import com.fxrates.data.repository.RatesRepositoryImpl
import com.fxrates.domain.repository.RatesRepository
import com.fxrates.root.RootUiComponent
import com.fxrates.root.RootUiComponentDefault
import io.ktor.client.HttpClient
import me.tatarka.inject.annotations.Component
import me.tatarka.inject.annotations.KmpComponentCreate
import me.tatarka.inject.annotations.Provides
import me.tatarka.inject.annotations.Scope
import kotlin.time.Clock

@Scope
@Target(AnnotationTarget.CLASS, AnnotationTarget.FUNCTION, AnnotationTarget.PROPERTY_GETTER)
internal annotation class AppScope

/** The application-wide graph. Bindings of a new feature are added here. */
@AppScope
@Component
internal abstract class AppComponent {

    abstract val rootFactory: RootUiComponentDefault.Factory

    @AppScope
    @Provides
    fun httpClient(): HttpClient = createHttpClient()

    @AppScope
    @Provides
    fun storeFactory(): StoreFactory = DefaultStoreFactory()

    @Provides
    fun clock(): Clock = Clock.System

    @AppScope
    @Provides
    fun RatesRepositoryImpl.bindRatesRepository(): RatesRepository = this

}

/** Generated by kotlin-inject for every target. */
@KmpComponentCreate
internal expect fun createAppComponent(): AppComponent

private val appComponent: AppComponent by lazy { createAppComponent() }

/** The entry point for the platform hosts: builds the root of the component tree. */
fun createRootComponent(componentContext: ComponentContext): RootUiComponent {
    return appComponent.rootFactory.create(componentContext)
}
